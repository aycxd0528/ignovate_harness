    assert.equal(await page.locator('.answer img,.answer script').count(),0);
    assert.equal(await page.locator('.answer a[href^="javascript:"]').count(),0);
    await page.locator('#token-weather').filter({hasText:'120'}).waitFor();
    const s=await snapshot(),first=s.branches.at(-1),node=s.nodes.find(n=>n.branch_id===first.id);
