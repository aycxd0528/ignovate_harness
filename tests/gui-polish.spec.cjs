    await page.locator('#dialog').getByRole('button',{name:'创建分支',exact:true}).click();
    await page.locator('#dialog').waitFor({state:'hidden'});
    await page.locator('#composer-target').filter({hasText:'方案 B'}).waitFor({state:'attached'});
    assert.equal(await page.locator('#permission-mode').getAttribute('data-value'),'default','forks must not inherit temporary permission mode');
    await page.getByRole('button',{name:'聊天',exact:true}).click();
    await page.locator('#composer').fill('B 方案后续');await page.getByRole('button',{name:'发送',exact:true}).click();
    await page.waitForFunction(async()=>{const s=await(await fetch('/api/snapshot',{headers:{Authorization:'Bearer browser-test-only'}})).json();return s.nodes.length===2});
